# ── Phase 1: Definition scanning ─────────────────────────────────

def _read_lines(path: Path) -> List[str]:
    return path.read_text(encoding="utf-8").splitlines()


def _register(registry: Dict[str, Artifact], art: Artifact, config: ProjectConfig):
    nid = normalize_id(art.id, config)
    art.id = nid
    if nid not in registry:
        registry[nid] = art


def scan_definitions(root: Path, config: ProjectConfig) -> Dict[str, Artifact]:
    """Scan artifact definitions using rules from config."""
    registry: Dict[str, Artifact] = {}

    for rule in config.definitions:
        file_str = rule.file
        # Support glob patterns in file field
        if '*' in file_str or '?' in file_str:
            # Glob: scan matching files
            matched = sorted(root.glob(file_str))
            for f in matched:
                if rule.mode == "heading":
                    _scan_heading(registry, f, rule.pattern, rule.type_id, config)
                elif rule.mode == "table":
                    _scan_table_first_col(registry, f, rule.pattern, rule.type_id, config)
        else:
            filepath = root / file_str
            if rule.mode == "heading":
                _scan_heading(registry, filepath, rule.pattern, rule.type_id, config)
            elif rule.mode == "table":
                _scan_table_first_col(registry, filepath, rule.pattern, rule.type_id, config)

    return registry


def _scan_heading(registry, filepath, pattern, type_id, config):
    if not filepath.exists():
        return
    for i, line in enumerate(_read_lines(filepath), 1):
        m = pattern.match(line)
        if m:
            raw_id = m.group(1)
            if raw_id is None:
                continue
            title = m.group(2).strip() if m.lastindex >= 2 else ""
            _register(registry, Artifact(raw_id, type_id, filepath, i, title), config)


def _scan_table_first_col(registry, filepath, pattern, type_id, config):
    if not filepath.exists():
        return
    for i, line in enumerate(_read_lines(filepath), 1):
        m = pattern.match(line)
        if m:
            raw_id = m.group(1)
            if raw_id is None:
                continue
            cols = [c.strip() for c in line.split("|")]
            title = cols[2] if len(cols) > 2 else ""
            _register(registry, Artifact(raw_id, type_id, filepath, i, title), config)


# ── Phase 2: Reference extraction ────────────────────────────────

def expand_ranges(text: str, config: ProjectConfig) -> List[str]:
    """Expand ranges like BR.12.1–BR.12.6 into individual IDs."""
    results = []
    for m in config.range_pattern.finditer(text):
        prefix, start_s, end_s = m.group(1), m.group(2), m.group(3)
        for i in range(int(start_s), int(end_s) + 1):
            results.append(f"{prefix}{i}")
    return results


def scan_index_cross_refs(
    root: Path, config: ProjectConfig
) -> List[Tuple[str, str, Path, int]]:
    """Parse index tables where first column is the 'source' artifact and other
    columns contain 'target' artifact IDs."""
    results: List[Tuple[str, str, Path, int]] = []

    for rule in config.index_tables:
        filepath = root / rule.file
        _parse_index_table(results, filepath, rule.first_col_pattern, config)

    return results


def _parse_index_table(
    results: List[Tuple[str, str, Path, int]],
    filepath: Path,
    first_col_re: re.Pattern,
    config: ProjectConfig,
):
    if not filepath.exists():
        return
    lines = _read_lines(filepath)
    for line_num, line in enumerate(lines, 1):
        m = first_col_re.match(line)
        if not m:
            continue
        source_id = normalize_id(m.group(1), config)
        rest = line[m.end():]

        # Find all artifact IDs in the rest of the row
        for tid, tdef in config.types.items():
            for rm in tdef.ref_pattern.finditer(rest):
                target_id = normalize_id(rm.group(1), config)
                if target_id != source_id:
                    results.append((source_id, target_id, filepath, line_num))

        # Also expand ranges
        for eid in expand_ranges(rest, config):
            nid = normalize_id(eid, config)
            if nid != source_id:
                results.append((source_id, nid, filepath, line_num))


def scan_references(
    root: Path,
    registry: Dict[str, Artifact],
    config: ProjectConfig,
) -> List[Reference]:
    """Scan all .md files for cross-references to known artifact types."""
    scan_dirs = [root / d for d in config.scan_dirs]
    md_files: List[Path] = []
    for d in scan_dirs:
        if d.exists():
            md_files.extend(sorted(d.rglob("*.md")))

    # Build restriction sets for types with restrict_to
    restrict_files: Dict[str, Set[Path]] = {}
    for tid, tdef in config.types.items():
        if tdef.restrict_to:
            files: Set[Path] = set()
            for pattern in tdef.restrict_to:
                p = root / pattern
                if p.is_file():
                    files.add(p)
                elif p.is_dir():
                    files.update(p.rglob("*.md"))
                else:
                    # Treat as glob
                    files.update(root.glob(pattern))
            restrict_files[tid] = files

    all_refs: List[Reference] = []

    for filepath in md_files:
        lines = _read_lines(filepath)
        in_code_fence = False
        current_section = ""

        for line_num, line in enumerate(lines, 1):
            stripped = line.strip()

            if stripped.startswith("```"):
                in_code_fence = not in_code_fence
                continue
            if in_code_fence:
                continue

            if stripped.startswith("## "):
                current_section = stripped.lstrip("# ").strip()

            # Expand ranges
            expanded = expand_ranges(line, config)
            for eid in expanded:
                nid = normalize_id(eid, config)
                all_refs.append(Reference(nid, filepath, line_num, current_section))

            # Match all type patterns
            for tid, tdef in config.types.items():
                # Check restriction
                if tid in restrict_files and filepath not in restrict_files[tid]:
                    continue

                for m in tdef.ref_pattern.finditer(line):
                    raw_id = m.group(1)
                    nid = normalize_id(raw_id, config)
                    all_refs.append(Reference(nid, filepath, line_num, current_section))

    return all_refs


# ── Phase 2b: Code / test reference extraction ───────────────────

def _scan_source_references(
    root: Path,
    dirs: List[str],
    extensions: List[str],
    extract_raw_ids,
    config: ProjectConfig,
) -> List[CodeReference]:
    """Generic per-line scanner over source files.

    `extract_raw_ids(line) -> List[str]` returns raw artifact ID candidates
    for a line; they are normalized and kept only if classifiable.
    """
    files: List[Path] = []
    for dir_str in dirs:
        d = root / dir_str
        if not d.exists():
            continue
        for ext in extensions:
            files.extend(sorted(d.rglob(f"*.{ext}")))

    return _scan_file_references(root, files, extract_raw_ids, config)


def _scan_file_references(
    root: Path,
    files: List[Path],
    extract_raw_ids,
    config: ProjectConfig,
) -> List[CodeReference]:
    results: List[CodeReference] = []

    for filepath in files:
        try:
            lines = filepath.read_text(encoding="utf-8").splitlines()
        except (UnicodeDecodeError, OSError):
            continue

        try:
            rel_path = str(filepath.relative_to(root))
        except ValueError:
            rel_path = str(filepath)

        for line_num, line in enumerate(lines, 1):
            target_ids = []
            for raw_id in extract_raw_ids(line):
                raw_id = raw_id.strip(".,;:")
                if not raw_id:
                    continue
                nid = normalize_id(raw_id, config)
                if classify_id(nid, config) is not None:
                    target_ids.append(nid)

            if target_ids:
                results.append(CodeReference(
                    code_file=filepath,
                    line_number=line_num,
                    target_ids=target_ids,
                    context=line.strip(),
                    rel_path=rel_path,
                ))

    return results


def scan_code_references(
    root: Path,
    config: ProjectConfig,
) -> List[CodeReference]:
    """Scan source code files for @trace comments referencing BA artifacts."""
    if not config.code or not config.code.comment_pattern:
        return []

    comment_re = config.code.comment_pattern

    def extract(line: str) -> List[str]:
        m = comment_re.match(line)
        if not m:
            return []
        raw_ids_str = m.group(1).strip()
        return [s.strip() for s in re.split(r'[,\s]+', raw_ids_str) if s.strip()]

    return _scan_source_references(
        root, config.code.dirs, config.code.extensions, extract, config)


def scan_test_references(
    root: Path,
    config: ProjectConfig,
) -> List[CodeReference]:
    """Scan test files for artifact ID references (TEST: nodes).

    Unlike code scanning, no @trace marker is required: any artifact ID
    matching a configured type ref pattern counts as test evidence.

    Files come from `dirs` (recursive, filtered by `extensions`) plus
    `files` glob patterns — the latter for colocated tests (e.g.
    `src/**/*.test.ts`) where scanning the whole dir would count ordinary
    source mentions as evidence.
    """
    if not config.tests:
        return []

    type_patterns = [tdef.ref_pattern for tdef in config.types.values()]

    def extract(line: str) -> List[str]:
        ids: List[str] = []
        for pattern in type_patterns:
            for m in pattern.finditer(line):
                ids.append(m.group(1))
        return ids

    refs = _scan_source_references(
        root, config.tests.dirs, config.tests.extensions, extract, config)

    if config.tests.files:
        glob_files: List[Path] = []
        for pattern in config.tests.files:
            glob_files.extend(sorted(root.glob(pattern)))
        seen = {r.code_file for r in refs}
        glob_files = [f for f in glob_files if f not in seen]
        refs.extend(_scan_file_references(root, glob_files, extract, config))

    return refs


def scan_ui_references(
    root: Path,
    config: ProjectConfig,
) -> List[CodeReference]:
    """Scan UI trace sidecar files for artifact ID references (UI: nodes).

    Files come from root-relative glob patterns in [ui].files. Like test
    scanning, no marker is required: any artifact ID matching a configured
    type ref pattern counts as a UI-to-artifact link.
    """
    if not config.ui:
        return []

    files: List[Path] = []
    for pattern in config.ui.files:
        files.extend(sorted(root.glob(pattern)))

    type_patterns = [tdef.ref_pattern for tdef in config.types.values()]

    def extract(line: str) -> List[str]:
        ids: List[str] = []
        for pattern in type_patterns:
            for m in pattern.finditer(line):
                ids.append(m.group(1))
        return ids

    return _scan_file_references(root, files, extract, config)


def scan_mini_registry_traces(
    root: Path,
    config: ProjectConfig,
) -> List[MiniRegistryTrace]:
    """Scan mini Resource(...) and CustomMethod(...) trace declarations.

    This is intentionally static AST parsing. graph-ba must not import a mini
    application just to learn its trace contract.
    """
    if not config.mini_registry:
        return []

    files: List[Path] = []
    for dir_str in config.mini_registry.dirs:
        d = root / dir_str
        if not d.exists():
            continue
        for ext in config.mini_registry.extensions:
            files.extend(sorted(d.rglob(f"*.{ext}")))
    for pattern in config.mini_registry.files:
        files.extend(sorted(root.glob(pattern)))

    seen: Set[Path] = set()
    traces: List[MiniRegistryTrace] = []
    for filepath in files:
        if filepath in seen or not filepath.is_file():
            continue
        seen.add(filepath)
        try:
            tree = ast.parse(filepath.read_text(encoding="utf-8"))
        except (SyntaxError, UnicodeDecodeError, OSError):
            continue
        try:
            rel_path = str(filepath.relative_to(root))
        except ValueError:
            rel_path = str(filepath)

        for node in ast.walk(tree):
            if not isinstance(node, ast.Call):
                continue
            call_name = _ast_call_name(node.func)
            if call_name == "Resource":
                source_key = _ast_kw_string(node, "name")
                title = _ast_kw_string(node, "title") or source_key or ""
                source_type = config.mini_registry.resource_type
                source_id = f"{source_type}:{source_key}" if source_key else ""
            elif call_name == "CustomMethod":
                source_key = _ast_kw_string(node, "code")
                title = _ast_kw_string(node, "title") or source_key or ""
                source_type = config.mini_registry.custom_method_type
                source_id = f"{source_type}:{source_key}" if source_key else ""
            else:
                continue
            if not source_id:
                continue

            links = _extract_trace_links(_ast_kw_value(node, "trace"))
            if not links:
                traces.append(MiniRegistryTrace(
                    source_id=source_id,
                    source_type=source_type,
                    title=title,
                    source_file=filepath,
                    line_number=getattr(node, "lineno", 0),
                    target_id="",
                    relation_type="",
                    context="mini_registry",
                    rel_path=rel_path,
                ))
                continue

            for raw_target, raw_relation in links:
                target_id = normalize_id(raw_target, config)
                if classify_id(target_id, config) is None:
                    continue
                traces.append(MiniRegistryTrace(
                    source_id=source_id,
                    source_type=source_type,
                    title=title,
                    source_file=filepath,
                    line_number=getattr(node, "lineno", 0),
                    target_id=target_id,
                    relation_type=_relation_type(raw_relation),
                    context="mini_registry_trace",
                    rel_path=rel_path,
                ))
    return traces


def scan_mini_admin_source_traces(
    root: Path,
    config: ProjectConfig,
) -> List[MiniAdminSourceTrace]:
    """Scan mini-admin `sources.ts` metadata into screen data dependencies.

    The scanner is intentionally static and literal-only. It understands the
    local source metadata style:
    - `resource: SOME_RESOURCES.key`
    - `derivedFrom: [SOME_RESOURCES.key, "resource_name"]`
    - `meta: { customMethods: ["method.code"] }`
    """
    if not config.mini_admin_sources:
        return []

    files: List[Path] = []
    for dir_str in config.mini_admin_sources.dirs:
        d = root / dir_str
        if not d.exists():
            continue
        for ext in config.mini_admin_sources.extensions:
            files.extend(sorted(d.rglob(f"*.{ext}")))
    for pattern in config.mini_admin_sources.files:
        files.extend(sorted(root.glob(pattern)))

    seen: Set[Path] = set()
    traces: List[MiniAdminSourceTrace] = []
    for filepath in files:
        if filepath in seen or not filepath.is_file():
            continue
        seen.add(filepath)
        try:
            text = filepath.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue
        try:
            rel_path = str(filepath.relative_to(root))
        except ValueError:
            rel_path = str(filepath)

        screen_id = _mini_admin_screen_id(filepath, root, config)
        if not screen_id:
            continue
        screen_type = classify_id(screen_id, config) or "SCREEN_FAMILY"
        constants_text = _read_sibling_ts_constants(filepath) + "\n" + text
        resource_constants = _extract_ts_resource_constants(constants_text)
        resources = _extract_ts_resources(text, resource_constants)
        custom_methods = _extract_ts_custom_methods(text)
        source_map = _extract_mini_admin_source_map(text, resource_constants)
        frontend_computed_sources = [
            key for key, value in source_map.items() if value.get("frontend_computed")
        ]
        title = screen_id

        for resource in sorted(resources):
            traces.append(MiniAdminSourceTrace(
                source_id=screen_id,
                source_type=screen_type,
                title=title,
                source_file=filepath,
                line_number=_line_number_for(text, resource),
                target_id=f"{config.mini_admin_sources.resource_type}:{resource}",
                target_type=config.mini_admin_sources.resource_type,
                relation_type=config.mini_admin_sources.relation_type,
                context="mini_admin_sources",
                rel_path=rel_path,
            ))
        for method_code in sorted(custom_methods):
            traces.append(MiniAdminSourceTrace(
                source_id=screen_id,
                source_type=screen_type,
                title=title,
                source_file=filepath,
                line_number=_line_number_for(text, method_code),
                target_id=f"{config.mini_admin_sources.custom_method_type}:{method_code}",
                target_type=config.mini_admin_sources.custom_method_type,
                relation_type=config.mini_admin_sources.relation_type,
                context="mini_admin_sources",
                rel_path=rel_path,
            ))
        for source_key in sorted(frontend_computed_sources):
            target_id = _frontend_computed_id(screen_id, source_key, config)
            traces.append(MiniAdminSourceTrace(
                source_id=screen_id,
                source_type=screen_type,
                title=title,
                source_file=filepath,
                line_number=_line_number_for(text, source_key),
                target_id=target_id,
                target_type=config.mini_admin_sources.frontend_computed_type,
                relation_type=config.mini_admin_sources.relation_type,
                context="mini_admin_sources",
                rel_path=rel_path,
            ))
    return traces


