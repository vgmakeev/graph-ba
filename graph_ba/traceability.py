def _collect_react_ui_aliases(
    root: Path,
    config: ProjectConfig,
) -> Dict[str, Set[str]]:
    """Map ordinary data-testid selectors to UIC aliases found on the same JSX tag."""
    aliases: Dict[str, Set[str]] = defaultdict(set)
    if not config.react_ui:
        return aliases
    files = _collect_configured_files(
        root,
        config.react_ui.dirs,
        config.react_ui.files,
        config.react_ui.extensions,
    )
    attr_re = re.compile(
        r"(?P<prop>data-testid|data-test-id|testID|data-uic-id)\s*=\s*"
        r"(?:\"(?P<double>[^\"]+)\"|'(?P<single>[^']+)'|\{\s*\"(?P<braced_double>[^\"]+)\"\s*\}|\{\s*'(?P<braced_single>[^']+)'\s*\})"
    )
    for filepath in files:
        try:
            text = _mask_js_comments(filepath.read_text(encoding="utf-8"))
        except (UnicodeDecodeError, OSError):
            continue
        for tag in re.finditer(r"<[A-Za-z][^<>]*?>", text, flags=re.DOTALL):
            attrs: Dict[str, List[str]] = defaultdict(list)
            for match in attr_re.finditer(tag.group(0)):
                value = next(
                    item for item in (
                        match.group("double"),
                        match.group("single"),
                        match.group("braced_double"),
                        match.group("braced_single"),
                    )
                    if item is not None
                )
                attrs[match.group("prop")].append(value)
            uic_values = [
                value for value in attrs.get("data-uic-id", [])
                if classify_id(normalize_id(value, config), config) == "UIC"
            ]
            test_values = attrs.get("data-testid", []) + attrs.get("data-test-id", []) + attrs.get("testID", [])
            for test_id in test_values:
                for uic in uic_values:
                    normalized_uic = normalize_id(uic, config)
                    aliases[test_id].add(normalized_uic)
                    aliases[normalized_uic].add(test_id)
    return aliases


def _component_aliases_for(selector: str, aliases: Dict[str, Set[str]]) -> List[str]:
    return sorted(aliases.get(selector, set()))


def _component_id_for(
    selector: str,
    aliases: List[str],
    config: ProjectConfig,
) -> str:
    for alias in aliases:
        normalized = normalize_id(alias, config)
        if classify_id(normalized, config) == "UIC":
            return normalized
    normalized = normalize_id(selector, config)
    if classify_id(normalized, config) == "UIC":
        return normalized
    prefix = config.mini_admin_sources.component_fallback_prefix if config.mini_admin_sources else "UIC:"
    return f"{prefix}{selector}"


def _trace_source_keys(raw_entry: Dict[str, object]) -> List[str]:
    values: List[str] = []
    source = raw_entry.get("source")
    if isinstance(source, str):
        values.append(source)
    sources = raw_entry.get("sources")
    if isinstance(sources, list):
        values.extend(item for item in sources if isinstance(item, str))
    return list(dict.fromkeys(values))


def _trace_string_array(value: object) -> List[str]:
    if not isinstance(value, list):
        return []
    return [item for item in value if isinstance(item, str)]


def _extract_mini_admin_source_map(
    text: str,
    constants: Dict[str, Dict[str, str]],
) -> Dict[str, Dict[str, object]]:
    body = _extract_first_ts_sources_object(text)
    if not body:
        return {}
    source_map: Dict[str, Dict[str, object]] = {}
    for key, value in _split_top_level_object_entries(body).items():
        source_map[key] = {
            "resources": _extract_ts_resources(value, constants),
            "custom_methods": _extract_ts_custom_methods(value),
            "frontend_computed": _is_frontend_computed_source(value),
        }
    return source_map


def _is_frontend_computed_source(value: str) -> bool:
    return (
        "computedFrontendDataSource" in value
        or re.search(r"\bkind\s*:\s*[\"']computed-frontend[\"']", value) is not None
    )


def _frontend_computed_id(screen_id: str, source_key: str, config: ProjectConfig) -> str:
    node_type = (
        config.mini_admin_sources.frontend_computed_type
        if config.mini_admin_sources else "FRONTEND_COMPUTED"
    )
    safe_key = re.sub(r"[^A-Za-z0-9_.:-]+", "-", source_key).strip("-")
    return f"{node_type}:{screen_id}:{safe_key}"


def _extract_first_ts_sources_object(text: str) -> str:
    match = re.search(r"(?:export\s+)?const\s+\w*Sources\s*=\s*\{", text)
    if not match:
        return ""
    open_index = text.find("{", match.start())
    close_index = _find_matching_brace(text, open_index)
    if close_index < 0:
        return ""
    return text[open_index + 1:close_index]


def _split_top_level_object_entries(body: str) -> Dict[str, str]:
    entries: Dict[str, str] = {}
    index = 0
    while index < len(body):
        while index < len(body) and body[index] in " \t\r\n,":
            index += 1
        key_match = re.match(r"([A-Za-z_$][A-Za-z0-9_$]*)\s*:", body[index:])
        if not key_match:
            index += 1
            continue
        key = key_match.group(1)
        value_start = index + key_match.end()
        value_end = _find_top_level_comma_or_end(body, value_start)
        entries[key] = body[value_start:value_end].strip()
        index = value_end + 1
    return entries


def _find_matching_brace(text: str, open_index: int) -> int:
    depth = 0
    quote = ""
    escaped = False
    for index in range(open_index, len(text)):
        char = text[index]
        if quote:
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == quote:
                quote = ""
            continue
        if char in "\"'`":
            quote = char
        elif char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                return index
    return -1


def _find_top_level_comma_or_end(text: str, start: int) -> int:
    depths = {"{": 0, "[": 0, "(": 0}
    quote = ""
    escaped = False
    for index in range(start, len(text)):
        char = text[index]
        if quote:
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == quote:
                quote = ""
            continue
        if char in "\"'`":
            quote = char
        elif char in depths:
            depths[char] += 1
        elif char == "}":
            if depths["{"] == 0 and depths["["] == 0 and depths["("] == 0:
                return index
            depths["{"] = max(0, depths["{"] - 1)
        elif char == "]":
            depths["["] = max(0, depths["["] - 1)
        elif char == ")":
            depths["("] = max(0, depths["("] - 1)
        elif char == "," and all(depth == 0 for depth in depths.values()):
            return index
    return len(text)


def _extract_ts_resource_constants(text: str) -> Dict[str, Dict[str, str]]:
    constants: Dict[str, Dict[str, str]] = {}
    pattern = re.compile(
        r"(?:export\s+)?const\s+([A-Z0-9_]*RESOURCES)\s*=\s*\{(?P<body>.*?)\}\s*as\s+const",
        re.DOTALL,
    )
    entry_pattern = re.compile(r"([A-Za-z0-9_]+)\s*:\s*[\"']([^\"']+)[\"']")
    for match in pattern.finditer(text):
        constants[match.group(1)] = {
            key: value for key, value in entry_pattern.findall(match.group("body"))
        }
    return constants


def _read_sibling_ts_constants(filepath: Path) -> str:
    chunks: List[str] = []
    for sibling_name in ("resources.ts", "resources.tsx"):
        sibling = filepath.with_name(sibling_name)
        if sibling == filepath or not sibling.is_file():
            continue
        try:
            chunks.append(sibling.read_text(encoding="utf-8"))
        except (UnicodeDecodeError, OSError):
            continue
    return "\n".join(chunks)


def _extract_ts_resources(text: str, constants: Dict[str, Dict[str, str]]) -> Set[str]:
    resources: Set[str] = set()
    for raw in re.findall(r"\bresource\s*:\s*([^,\n}]+)", text):
        value = _resolve_ts_resource_expr(raw, constants)
        if value:
            resources.add(value)
    for raw_array in re.findall(r"\bderivedFrom\s*:\s*\[(.*?)\]", text, flags=re.DOTALL):
        for raw_item in raw_array.split(","):
            value = _resolve_ts_resource_expr(raw_item, constants)
            if value and ":" not in value:
                resources.add(value)
    return resources


def _extract_ts_custom_methods(text: str) -> Set[str]:
    methods: Set[str] = set()
    for raw_array in re.findall(r"\bcustomMethods\s*:\s*\[(.*?)\]", text, flags=re.DOTALL):
        for value in re.findall(r"[\"']([^\"']+)[\"']", raw_array):
            if value:
                methods.add(value)
    for value in re.findall(r"\bcustomMethod\s*:\s*[\"']([^\"']+)[\"']", text):
        if value:
            methods.add(value)
    return methods


def _resolve_ts_resource_expr(raw: str, constants: Dict[str, Dict[str, str]]) -> str:
    expr = raw.strip().rstrip(",")
    literal = re.match(r"^[\"']([^\"']+)[\"']$", expr)
    if literal:
        return literal.group(1)
    attr = re.match(r"^([A-Z0-9_]*RESOURCES)\.([A-Za-z0-9_]+)$", expr)
    if attr:
        return constants.get(attr.group(1), {}).get(attr.group(2), "")
    return ""


def _line_number_for(text: str, needle: str) -> int:
    index = text.find(needle)
    if index < 0:
        return 0
    return text.count("\n", 0, index) + 1


def scan_react_ui_elements(
    root: Path,
    config: ProjectConfig,
) -> List[ReactUiElement]:
    """Scan React JSX UI trace attributes.

    This scanner intentionally imports only literal attribute values selected by
    `[react_ui]` patterns unless `include_unmatched=true`.
    """
    if not config.react_ui:
        return []

    files = _collect_configured_files(
        root,
        config.react_ui.dirs,
        config.react_ui.files,
        config.react_ui.extensions,
    )
    prop_roles = _react_ui_prop_roles(config)
    prop_re = "|".join(re.escape(prop) for prop in prop_roles)
    if not prop_re:
        return []
    attr_re = re.compile(
        rf"(?P<prop>{prop_re})\s*=\s*"
        r"(?:"
        r"\"(?P<double>[^\"]+)\""
        r"|'(?P<single>[^']+)'"
        r"|\{\s*\"(?P<braced_double>[^\"]+)\"\s*\}"
        r"|\{\s*'(?P<braced_single>[^']+)'\s*\}"
        r"|\{\s*`(?P<braced_template>[^`$]+)`\s*\}"
        r")"
    )
    component_include_res = [
        re.compile(pattern) for pattern in config.react_ui.include_patterns
    ]
    screen_include_res = [
        re.compile(pattern) for pattern in config.react_ui.screen_include_patterns
    ]
    screen_family_include_res = [
        re.compile(pattern)
        for pattern in config.react_ui.screen_family_include_patterns
    ]

    elements: List[ReactUiElement] = []
    for filepath in files:
        try:
            text = filepath.read_text(encoding="utf-8")
        except (UnicodeDecodeError, OSError):
            continue
        masked = _mask_js_comments(text)
        try:
            rel_path = str(filepath.relative_to(root))
        except ValueError:
            rel_path = str(filepath)
        source_id = f"REACT:{rel_path}"

        for match in attr_re.finditer(masked):
            selector = next(
                value for value in (
                    match.group("double"),
                    match.group("single"),
                    match.group("braced_double"),
                    match.group("braced_single"),
                    match.group("braced_template"),
                )
                if value is not None
            )
            role = prop_roles[match.group("prop")]
            if role == "screen_family":
                include_res = screen_family_include_res
                fallback_type = config.react_ui.screen_family_type
                relation_type = config.react_ui.screen_relation_type
            elif role == "screen":
                include_res = screen_include_res
                fallback_type = config.react_ui.screen_type
                relation_type = config.react_ui.screen_relation_type
            else:
                include_res = component_include_res
                fallback_type = config.react_ui.selector_type
                relation_type = config.react_ui.relation_type

            if not _react_selector_included(
                selector,
                include_res,
                config.react_ui.include_unmatched,
            ):
                continue

            normalized = normalize_id(selector, config)
            target_type = classify_id(normalized, config)
            target_id = normalized
            if target_type is None:
                if not config.react_ui.include_unmatched:
                    continue
                target_type = fallback_type
                target_id = f"{target_type}:{selector}"

            line_number = masked.count("\n", 0, match.start()) + 1
            elements.append(ReactUiElement(
                source_id=source_id,
                source_type=config.react_ui.source_type,
                source_file=filepath,
                line_number=line_number,
                selector=selector,
                target_id=target_id,
                target_type=target_type,
                relation_type=relation_type,
                role=role,
                context=f"{match.group('prop')}={selector}",
                rel_path=rel_path,
            ))
    return elements


def _react_ui_prop_roles(config: ProjectConfig) -> Dict[str, str]:
    if not config.react_ui:
        return {}
    roles: Dict[str, str] = {}
    for prop in config.react_ui.props:
        roles[prop] = "component"
    for prop in config.react_ui.screen_props:
        roles[prop] = "screen"
    for prop in config.react_ui.screen_family_props:
        roles[prop] = "screen_family"
    return roles


def _collect_configured_files(
    root: Path,
    dirs: List[str],
    files: List[str],
    extensions: List[str],
) -> List[Path]:
    collected: List[Path] = []
    for dir_str in dirs:
        d = root / dir_str
        if not d.exists():
            continue
        for ext in extensions:
            collected.extend(sorted(d.rglob(f"*.{ext}")))
    for pattern in files:
        collected.extend(sorted(root.glob(pattern)))
    seen: Set[Path] = set()
    result: List[Path] = []
    for item in collected:
        if item in seen or not item.is_file():
            continue
        seen.add(item)
        result.append(item)
    return result


def _react_selector_included(
    selector: str,
    include_res: List[re.Pattern],
    include_unmatched: bool,
) -> bool:
    if include_unmatched:
        return True
    return any(pattern.search(selector) for pattern in include_res)


def _mask_js_comments(text: str) -> str:
    """Replace JS/TS comments with spaces while preserving line offsets."""
    result: List[str] = []
    i = 0
    state = "normal"
    quote = ""
    while i < len(text):
        ch = text[i]
        nxt = text[i + 1] if i + 1 < len(text) else ""

        if state == "line_comment":
            if ch == "\n":
                state = "normal"
                result.append(ch)
            else:
                result.append(" ")
            i += 1
            continue

        if state == "block_comment":
            if ch == "*" and nxt == "/":
                result.extend("  ")
                state = "normal"
                i += 2
            else:
                result.append("\n" if ch == "\n" else " ")
                i += 1
            continue

        if state == "string":
            result.append(ch)
            if ch == "\\" and i + 1 < len(text):
                result.append(text[i + 1])
                i += 2
                continue
            if ch == quote:
                state = "normal"
            i += 1
            continue

        if ch in {"'", '"', "`"}:
            state = "string"
            quote = ch
            result.append(ch)
            i += 1
            continue
        if ch == "/" and nxt == "/":
            result.extend("  ")
            state = "line_comment"
            i += 2
            continue
        if ch == "/" and nxt == "*":
            result.extend("  ")
            state = "block_comment"
            i += 2
            continue
        result.append(ch)
        i += 1
    return "".join(result)


def _ast_call_name(func: ast.expr) -> str:
    if isinstance(func, ast.Name):
        return func.id
    if isinstance(func, ast.Attribute):
        return func.attr
    return ""


def _ast_kw_value(call: ast.Call, name: str) -> ast.expr | None:
    for kw in call.keywords:
        if kw.arg == name:
            return kw.value
    return None


def _ast_kw_string(call: ast.Call, name: str) -> str | None:
    value = _ast_kw_value(call, name)
    return value.value if isinstance(value, ast.Constant) and isinstance(value.value, str) else None


def _ast_string(value: ast.expr | None) -> str | None:
    if isinstance(value, ast.Constant) and isinstance(value.value, str):
        return value.value
    return None


def _ast_string_items(value: ast.expr | None) -> List[str]:
    if isinstance(value, (ast.Tuple, ast.List, ast.Set)):
        return [item.value for item in value.elts
                if isinstance(item, ast.Constant) and isinstance(item.value, str)]
    single = _ast_string(value)
    return [single] if single else []


def _extract_trace_links(value: ast.expr | None) -> List[Tuple[str, str]]:
    if value is None:
        return []
    if not isinstance(value, ast.Call):
        return []
    call_name = _ast_call_name(value.func)

    # Traceability.implements("AC-...")
    if (
        isinstance(value.func, ast.Attribute)
        and value.func.attr == "implements"
        and _ast_call_name(value.func.value) == "Traceability"
    ):
        artifacts = [
            artifact for artifact in (_ast_string(arg) for arg in value.args)
            if artifact is not None
        ]
        return [(artifact, "implements") for artifact in artifacts]

    if call_name != "Traceability":
        return []

    links: List[Tuple[str, str]] = []
    artifacts_value = _ast_kw_value(value, "artifacts")
    for artifact in _ast_string_items(artifacts_value):
        links.append((artifact, "implements"))

    links_value = _ast_kw_value(value, "links")
    if isinstance(links_value, (ast.Tuple, ast.List, ast.Set)):
        for item in links_value.elts:
            parsed = _extract_trace_link(item)
            if parsed:
                links.append(parsed)
    return links


def _extract_trace_link(value: ast.expr) -> Tuple[str, str] | None:
    if not isinstance(value, ast.Call) or _ast_call_name(value.func) != "TraceLink":
        return None
    artifact = _ast_kw_string(value, "artifact")
    if artifact is None and value.args:
        artifact = _ast_string(value.args[0])
    relation = _ast_kw_string(value, "relation")
    if relation is None and len(value.args) > 1:
        relation = _ast_string(value.args[1])
    if not artifact:
        return None
    return artifact, relation or "implements"


def _relation_type(raw: str) -> str:
    value = re.sub(r"[^A-Za-z0-9]+", "_", raw.strip()).strip("_").upper()
    return value or "IMPLEMENTS"


# ── Phase 3: Graph construction ──────────────────────────────────

def _find_owner(
    file_arts: List[Tuple[int, str]],
    ref_line: int,
) -> Optional[str]:
    if not file_arts:
        return None
    if len(file_arts) == 1:
        return file_arts[0][1]
    best = None
    for def_line, aid in file_arts:
        if def_line <= ref_line:
            best = aid
        else:
            break
    return best


def build_graph(
    registry: Dict[str, Artifact],
    references: List[Reference],
    config: ProjectConfig,
    index_xrefs: Optional[List[Tuple[str, str, Path, int]]] = None,
    code_refs: Optional[List[CodeReference]] = None,
    test_refs: Optional[List[CodeReference]] = None,
    ui_refs: Optional[List[CodeReference]] = None,
    mini_registry_traces: Optional[List[MiniRegistryTrace]] = None,
    react_ui_elements: Optional[List[ReactUiElement]] = None,
    mini_admin_source_traces: Optional[List[MiniAdminSourceTrace]] = None,
    mini_admin_component_traces: Optional[List[MiniAdminComponentTrace]] = None,
) -> nx.DiGraph:
    G = nx.DiGraph()

    for aid, art in registry.items():
        origin = config.types.get(art.artifact_type).origin if art.artifact_type in config.types else ""
        G.add_node(aid, type=art.artifact_type, title=art.title,
                   source_file=str(art.source_file.name), origin=origin)

    file_arts_map: Dict[Path, List[Tuple[int, str]]] = defaultdict(list)
    for aid, art in registry.items():
        file_arts_map[art.source_file].append((art.line_number, aid))
    for k in file_arts_map:
        file_arts_map[k].sort()

    for ref in references:
        target = ref.target_id
        if target not in G:
            atype = classify_id(target, config)
            origin = config.types.get(atype).origin if atype in config.types else ""
            G.add_node(target, type=atype or "UNKNOWN",
                       title="", source_file="", defined=False, origin=origin)

        file_arts = file_arts_map.get(ref.source_file)
        owner = _find_owner(file_arts, ref.line_number) if file_arts else None

        if owner and owner != target:
            G.add_edge(owner, target, context=ref.context,
                       source_file=str(ref.source_file.name),
                       line=ref.line_number,
                       relation_type="MENTIONS")
        elif not owner:
            file_node = f"FILE:{ref.source_file.name}"
            if not G.has_node(file_node):
                G.add_node(file_node, type="FILE", title=ref.source_file.name,
                           source_file=str(ref.source_file.name), defined=True,
                           origin="container")
            if target != file_node:
                G.add_edge(file_node, target, context=ref.context,
                           source_file=str(ref.source_file.name),
                           line=ref.line_number,
                           relation_type="MENTIONS")

    if index_xrefs:
        for src, tgt, fpath, lnum in index_xrefs:
            if tgt not in G:
                atype = classify_id(tgt, config)
                origin = config.types.get(atype).origin if atype in config.types else ""
                G.add_node(tgt, type=atype or "UNKNOWN",
                           title="", source_file="", defined=False, origin=origin)
            if src not in G:
                continue
            if src != tgt:
                G.add_edge(src, tgt, context="index_table",
                           source_file=str(fpath.name), line=lnum,
                           relation_type="INDEX")

    # ── Code references → CODE nodes, test references → TEST nodes,
    #    UI trace references → UI nodes ──
    _add_source_ref_nodes(G, code_refs, "CODE:", "CODE", config,
                          relation_type="CODE_TRACE", origin="implementation")
    _add_source_ref_nodes(G, test_refs, "TEST:", "TEST", config,
                          relation_type="TEST_EVIDENCE", origin="evidence")
    _add_source_ref_nodes(G, ui_refs, "UI:", "UI", config,
                          relation_type="UI_TRACE", origin="evidence")
    _add_mini_registry_nodes(G, mini_registry_traces, config)
    _add_react_ui_nodes(G, react_ui_elements, config)
    _add_mini_admin_source_nodes(G, mini_admin_source_traces, config)
    _add_mini_admin_component_trace_nodes(G, mini_admin_component_traces, config)

    for aid in registry:
        G.nodes[aid]["defined"] = True

    _resolve_dangling_variants(G, registry)

    return G


def _add_react_ui_nodes(
    G: nx.DiGraph,
    elements: Optional[List[ReactUiElement]],
    config: ProjectConfig,
):
    if not elements:
        return
    by_source: Dict[str, List[ReactUiElement]] = defaultdict(list)
    for element in elements:
        by_source[element.source_id].append(element)
        origin = config.react_ui.origin if config.react_ui else "implementation"
        if not G.has_node(element.source_id):
            G.add_node(element.source_id, type=element.source_type, title=element.rel_path,
                       source_file=element.rel_path, defined=True, origin=origin)

        if element.target_id not in G:
            target_origin = (
                config.types.get(element.target_type).origin
                if element.target_type in config.types
                else origin
            )
            G.add_node(element.target_id, type=element.target_type, title=element.selector,
                       source_file=element.rel_path, defined=True, origin=target_origin)

        G.add_edge(element.source_id, element.target_id,
                   context=element.context,
                   source_file=element.rel_path,
                   line=element.line_number,
                   relation_type=element.relation_type)

    for source_elements in by_source.values():
        _add_react_ui_ownership_edges(G, source_elements, config)


def _add_react_ui_ownership_edges(
    G: nx.DiGraph,
    elements: List[ReactUiElement],
    config: ProjectConfig,
):
    families = [e for e in elements if e.role == "screen_family"]
    screens = [e for e in elements if e.role == "screen"]
    components = [e for e in elements if e.role == "component"]
    if not config.react_ui:
        return

    for family in families:
        for screen in screens:
            if family.target_id == screen.target_id:
                continue
            G.add_edge(family.target_id, screen.target_id,
                       context="same React source",
                       source_file=screen.rel_path,
                       line=screen.line_number,
                       relation_type=config.react_ui.screen_family_relation_type)

    owners = screens if screens else families
    for owner in owners:
        for component in components:
            if owner.target_id == component.target_id:
                continue
            G.add_edge(owner.target_id, component.target_id,
                       context="same React source",
                       source_file=component.rel_path,
                       line=component.line_number,
                       relation_type=config.react_ui.screen_component_relation_type)


def _add_mini_registry_nodes(
    G: nx.DiGraph,
    traces: Optional[List[MiniRegistryTrace]],
    config: ProjectConfig,
):
    if not traces:
        return
    for trace in traces:
        if not G.has_node(trace.source_id):
            origin = config.mini_registry.origin if config.mini_registry else "implementation"
            G.add_node(trace.source_id, type=trace.source_type, title=trace.title,
                       source_file=trace.rel_path, defined=True, origin=origin)
        if not trace.target_id:
            continue
        if trace.target_id not in G:
            atype = classify_id(trace.target_id, config)
            target_origin = config.types.get(atype).origin if atype in config.types else ""
            G.add_node(trace.target_id, type=atype or "UNKNOWN",
                       title="", source_file="", defined=False,
                       origin=target_origin)
        G.add_edge(trace.source_id, trace.target_id,
                   context=trace.context,
                   source_file=trace.rel_path,
                   line=trace.line_number,
                   relation_type=trace.relation_type)


def _add_mini_admin_source_nodes(
    G: nx.DiGraph,
    traces: Optional[List[MiniAdminSourceTrace]],
    config: ProjectConfig,
):
    if not traces:
        return
    for trace in traces:
        origin = (
            config.mini_admin_sources.origin
            if config.mini_admin_sources
            else "implementation"
        )
        if not G.has_node(trace.source_id):
            G.add_node(trace.source_id, type=trace.source_type, title=trace.title,
                       source_file=trace.rel_path, defined=True, origin=origin)
        if not G.has_node(trace.target_id):
            G.add_node(trace.target_id, type=trace.target_type, title=trace.target_id,
                       source_file=trace.rel_path, defined=True, origin=origin)
        G.add_edge(trace.source_id, trace.target_id,
                   context=trace.context,
                   source_file=trace.rel_path,
                   line=trace.line_number,
                   relation_type=trace.relation_type)


def _add_mini_admin_component_trace_nodes(
    G: nx.DiGraph,
    traces: Optional[List[MiniAdminComponentTrace]],
    config: ProjectConfig,
):
    if not traces:
        return
    origin = (
        config.mini_admin_sources.origin
        if config.mini_admin_sources
        else "implementation"
    )
    component_type = (
        config.mini_admin_sources.component_type
        if config.mini_admin_sources
        else "UIC"
    )
    component_relation_type = (
        config.mini_admin_sources.component_relation_type
        if config.mini_admin_sources
        else "CONTAINS"
    )
    seen_containment: Set[Tuple[str, str]] = set()
    for trace in traces:
        if not G.has_node(trace.screen_id):
            screen_type = classify_id(trace.screen_id, config) or "SCREEN_FAMILY"
            G.add_node(trace.screen_id, type=screen_type, title=trace.screen_id,
                       source_file=trace.rel_path, defined=True, origin=origin)
        if not G.has_node(trace.component_id):
            G.add_node(trace.component_id, type=component_type, title=trace.component_selector,
                       source_file=trace.rel_path, defined=True, origin=origin)
        containment_key = (trace.screen_id, trace.component_id)
        if containment_key not in seen_containment:
            G.add_edge(trace.screen_id, trace.component_id,
                       context="mini_admin_component_trace",
                       source_file=trace.rel_path,
                       line=trace.line_number,
                       relation_type=component_relation_type)
            seen_containment.add(containment_key)
        if not G.has_node(trace.target_id):
            G.add_node(trace.target_id, type=trace.target_type, title=trace.target_id,
                       source_file=trace.rel_path, defined=True, origin=origin)
        G.add_edge(trace.component_id, trace.target_id,
                   context=trace.context,
                   source_file=trace.rel_path,
                   line=trace.line_number,
                   relation_type=trace.relation_type)


def _add_source_ref_nodes(
    G: nx.DiGraph,
    refs: Optional[List[CodeReference]],
    prefix: str,
    node_type: str,
    config: ProjectConfig,
    relation_type: str,
    origin: str,
):
    """Add meta-nodes (CODE:/TEST:) with edges to referenced artifacts."""
    if not refs:
        return
    for cref in refs:
        node_id = f"{prefix}{cref.rel_path}"
        if not G.has_node(node_id):
            G.add_node(node_id, type=node_type, title=cref.rel_path,
                       source_file=cref.rel_path, defined=True,
                       origin=origin)
        for target_id in cref.target_ids:
            if target_id not in G:
                atype = classify_id(target_id, config)
                target_origin = config.types.get(atype).origin if atype in config.types else ""
                G.add_node(target_id, type=atype or "UNKNOWN",
                           title="", source_file="", defined=False,
                           origin=target_origin)
            G.add_edge(node_id, target_id,
                       context=cref.context,
                       source_file=cref.rel_path,
                       line=cref.line_number,
                       relation_type=relation_type)


def _resolve_dangling_variants(G: nx.DiGraph, registry: Dict[str, Artifact]):
    """If an ID is referenced but not defined, link to its variants if they exist.

    E.g. BP-01 → BP-01a, BP-01b.
    """
    dangling = [
        n for n in G.nodes()
        if not G.nodes[n].get("defined", False) and not n.startswith("FILE:")
    ]
    for node_id in dangling:
        variants = [aid for aid in registry if aid.startswith(node_id) and aid != node_id]
        if not variants:
            continue
        preds = list(G.predecessors(node_id))
        for pred in preds:
            edge_data = G.edges[pred, node_id]
            for var in variants:
                if pred != var:
                    G.add_edge(pred, var, **edge_data)
        succs = list(G.successors(node_id))
        for succ in succs:
            edge_data = G.edges[node_id, succ]
            for var in variants:
                if var != succ:
                    G.add_edge(var, succ, **edge_data)
        G.remove_node(node_id)


# ── Phase 4: Verification checks ────────────────────────────────

@dataclass
class TraceReport:
    registry_count: Dict[str, int] = field(default_factory=dict)
    total_edges: int = 0
    orphans: List[str] = field(default_factory=list)
    dangling: List[Tuple[str, str, int]] = field(default_factory=list)
    coverage: Dict[str, dict] = field(default_factory=dict)
    missing_expected: List[Tuple[str, str]] = field(default_factory=list)


def verify(
    G: nx.DiGraph,
    registry: Dict[str, Artifact],
    references: List[Reference],
    config: ProjectConfig,
) -> TraceReport:
    report = TraceReport()

    type_counts: Dict[str, int] = defaultdict(int)
    for art in registry.values():
        type_counts[art.artifact_type] += 1
    report.registry_count = dict(type_counts)
    report.total_edges = G.number_of_edges()

    for aid in registry:
        if G.in_degree(aid) == 0:
            report.orphans.append(aid)

    defined_ids = set(registry.keys())
    dangling_ids: Set[str] = set()
    for ref in references:
        if ref.target_id not in defined_ids:
            if ref.target_id in G:
                continue
            dangling_ids.add(ref.target_id)

    dangling_first: Dict[str, Tuple[str, int]] = {}
    for ref in references:
        if ref.target_id in dangling_ids and ref.target_id not in dangling_first:
            dangling_first[ref.target_id] = (str(ref.source_file.name), ref.line_number)
    for did, (fname, lnum) in sorted(dangling_first.items()):
        report.dangling.append((did, fname, lnum))

    # Coverage matrix from config
    for cp in config.coverage_pairs:
        src_type, tgt_type, label = cp.source, cp.target, cp.label
        src_ids = [aid for aid, art in registry.items() if art.artifact_type == src_type]
        linked = []
        missing = []
        for sid in src_ids:
            if sid in G:
                has_link = any(
                    G.nodes.get(t, {}).get("type") == tgt_type
                    for t in G.successors(sid)
                )
                if has_link:
                    linked.append(sid)
                else:
                    missing.append(sid)
            else:
                missing.append(sid)
        total = len(src_ids)
        pct = (len(linked) / total * 100) if total > 0 else 0
        report.coverage[label] = {
            "total": total,
            "linked": len(linked),
            "pct": round(pct, 1),
            "missing": missing,
        }

    # Missing expected links from config
    for atype, expected in config.expected_cross_layer.items():
        for aid, art in registry.items():
            if art.artifact_type != atype or aid not in G:
                continue
            for target_type, label in expected:
                if not any(G.nodes.get(t, {}).get("type") == target_type
                           for t in G.successors(aid)):
                    report.missing_expected.append((aid, f"{target_type} ({label})"))

    return report


# ── Output: Console report ───────────────────────────────────────

def print_report(report: TraceReport, registry: Dict[str, Artifact],
                 config: ProjectConfig, verbose: bool):
    print("=" * 60)
    print("  Traceability Report")
    print(f"  Generated: {datetime.now().strftime('%Y-%m-%d %H:%M')}")
    print("=" * 60)

    print("\n--- Registry Summary ---")
    total = 0
    for tid in config.type_order:
        cnt = report.registry_count.get(tid, 0)
        total += cnt
        label = config.types[tid].label if tid in config.types else tid
        print(f"  {label:40s} {cnt:>4d}")
    # Types not in config (shouldn't happen, but be safe)
    for tid, cnt in report.registry_count.items():
        if tid not in config.type_order:
            print(f"  {tid:40s} {cnt:>4d}")
            total += cnt
    print(f"  {'TOTAL':40s} {total:>4d} artifacts, {report.total_edges} edges")

    print("\n--- Coverage Matrix ---")
    for label, data in report.coverage.items():
        status = "OK" if data["pct"] >= 100 else f"WARN: {len(data['missing'])} missing"
        bar = f"{data['linked']}/{data['total']} ({data['pct']}%)"
        print(f"  {label:25s} {bar:>20s}  [{status}]")
        if verbose and data["missing"]:
            for mid in data["missing"]:
                print(f"       - {mid}")

    if report.dangling:
        print(f"\n--- Dangling References ({len(report.dangling)}) ---")
        for did, fname, lnum in report.dangling:
            print(f"  [ERROR] {did} referenced in {fname}:{lnum} but NOT defined")
    else:
        print("\n--- Dangling References: none ---")

    if report.orphans:
        print(f"\n--- Orphan Artifacts ({len(report.orphans)}) ---")
        orphan_types = defaultdict(list)
        for oid in report.orphans:
            if oid in registry:
                orphan_types[registry[oid].artifact_type].append(oid)
        for tval, ids in sorted(orphan_types.items()):
            print(f"  [{tval}] ({len(ids)}): {', '.join(sorted(ids))}")
    else:
        print("\n--- Orphan Artifacts: none ---")

    if report.missing_expected:
        print(f"\n--- Missing Expected Links ({len(report.missing_expected)}) ---")
        for aid, missing_type in sorted(report.missing_expected):
            print(f"  [WARN] {aid} has no link to {missing_type}")
    else:
        print("\n--- Missing Expected Links: none ---")

    errors = len(report.dangling)
    warnings = len(report.orphans) + len(report.missing_expected)
    ok_pairs = sum(1 for d in report.coverage.values() if d["pct"] >= 100)
    print(f"\n{'=' * 60}")
    print(f"  {errors} errors, {warnings} warnings, "
          f"{ok_pairs}/{len(report.coverage)} coverage pairs at 100%")
    print(f"{'=' * 60}")


